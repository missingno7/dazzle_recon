"""Regenerate native/src/app/pending.c: stubs for declared but not yet ported symbols.

While modules are ported in parallel, the native program must still link. Every function or object
declared `extern` in native/include/dazzle.h (single-line declarations) that no other native source
defines gets a stub here, grouped by the original src/ module that owns it. Function stubs abort with the
symbol name; object stubs are zero-initialised. Porters delete the stubs of the symbols they port;
the supervisor reruns this script after merging.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NATIVE = ROOT / 'native'
OUT = NATIVE / 'src/app/pending.c'
DECL = re.compile(r'^extern\s+(.+?);\s*(?:/\*.*\*/)?\s*$')
TYPES = set('void char short int long float double signed unsigned const volatile int8_t uint8_t int16_t '
            'uint16_t int32_t uint32_t int64_t uint64_t size_t FILE'.split())


def strip_comments(text):
    return re.sub(r'/\*.*?\*/', '', text, flags=re.S)


def declarations():
    out = {}
    for line in strip_comments((NATIVE / 'include/dazzle.h').read_text(encoding='utf-8')).splitlines():
        m = DECL.match(line.strip())
        if not m or 'typedef' in line:
            continue
        body = m.group(1)
        f = re.match(r'^(.*?[\s*])([A-Za-z_]\w*)\s*\((.*)\)$', body)
        if f and '(*' not in f.group(1):
            out[f.group(2)] = ('func', f.group(1).strip(), f.group(3).strip())
            continue
        d = re.match(r'^(.*?)\b([A-Za-z_]\w*)\s*(\[.*\])?$', body)
        if d and '(' not in body:
            out[d.group(2)] = ('data', body, None)
        elif '(*' in body:  # function-pointer object
            name = re.search(r'\(\s*\*\s*([A-Za-z_]\w*)\s*\)', body)
            if name:
                out[name.group(1)] = ('data', body, None)
    return out


def defined_elsewhere():
    """Names defined at file scope by native sources other than pending.c (textual scan)."""
    names = set()
    for path in NATIVE.glob('src/**/*.c'):
        if path == OUT:
            continue
        text = strip_comments(path.read_text(encoding='utf-8'))
        for line in text.splitlines():
            if not line or line[0] in ' \t#}/' or line.startswith(('extern', 'typedef', 'static inline')):
                continue
            if line.rstrip().endswith(';') and '(' in line and '=' not in line and not re.search(r'\(\s*\*', line):
                continue  # prototype
            for name in re.findall(r'\b([A-Za-z_]\w*)\s*(?:\(|\[|=|;|,)', line):
                names.add(name)
            m = re.search(r'\(\s*\*\s*([A-Za-z_]\w*)\s*\)', line)
            if m:
                names.add(m.group(1))
    return names


def owner(name, sources):
    pat = re.compile(r'^(?!extern|typedef|static inline)[^ \t#/}].*\b' + re.escape(name) + r'\b')
    for module, text in sources.items():
        for line in text.splitlines():
            if pat.match(line) and not (line.rstrip().endswith(';') and name + '(' in line.replace(' (', '(')):
                return module
    return 'unknown'


def params(text):
    if text in ('', 'void'):
        return 'void', []
    parts, depth, cur = [], 0, ''
    for ch in text:
        depth += ch == '('
        depth -= ch == ')'
        if ch == ',' and depth == 0:
            parts.append(cur.strip())
            cur = ''
        else:
            cur += ch
    parts.append(cur.strip())
    named, uses = [], []
    for i, p in enumerate(parts):
        if p == '...':
            named.append(p)
            continue
        fp = re.search(r'\(\s*\*\s*([A-Za-z_]\w*)?\s*\)', p)
        if fp:
            if not fp.group(1):
                p = p.replace(fp.group(0), f'(*p{i})', 1)
            named.append(p)
            uses.append(fp.group(1) or f'p{i}')
            continue
        tokens = re.findall(r'[A-Za-z_]\w*', p)
        last = tokens[-1] if tokens else ''
        if (len(tokens) < 2 or last in TYPES or p.rstrip().endswith('*') or
                (len(tokens) == 2 and tokens[0] in ('struct', 'union', 'enum'))):
            named.append(f'{p} p{i}')
            uses.append(f'p{i}')
        else:
            named.append(p)
            uses.append(last)
    return ', '.join(named), uses


def main():
    decls = declarations()
    defined = defined_elsewhere()
    sources = {p.stem: p.read_text(encoding='utf-8') for p in sorted((ROOT / 'src').glob('*.c'))}
    sources['dvdt'] = (ROOT / 'asm/dvdt.asm').read_text(encoding='utf-8')
    groups = {}
    for name, decl in sorted(decls.items()):
        if name not in defined:
            groups.setdefault(owner(name, sources), []).append((name, decl))
    lines = ['/* Generated by tools/native_pending.py: stubs for symbols not yet ported.',
             ' * Porters: delete the stubs of the symbols you port (only in your module group).',
             ' * Function stubs abort; object stubs are zero-initialised. */',
             '#include "dazzle.h"', '#include <stdio.h>', '#include <stdlib.h>', '',
             'static void pending(const char *name)', '{',
             '    fprintf(stderr, "DAZZLE native: %s is not ported yet\\n", name);', '    abort();', '}']
    total = 0
    for module in sorted(groups):
        lines += ['', f'/* ---- {module} ---- */']
        for name, (kind, a, b) in groups[module]:
            total += 1
            if kind == 'data':
                lines.append(a + ';')
                continue
            plist, uses = params(b)
            casts = ''.join(f' (void){u};' for u in uses)
            ret = '' if a == 'void' else ' return 0;'
            lines.append(f'{a} {name}({plist}) {{{casts} pending("{name}");{ret} }}')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{OUT.relative_to(ROOT)}: {total} pending symbols in {len(groups)} groups')
    for module in sorted(groups):
        print(f'  {module}: {len(groups[module])}')


if __name__ == '__main__':
    sys.exit(main())
