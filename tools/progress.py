"""Authoritative progress rollup from strict receipts -> docs/PROGRESS.md.

Units are real module extents taken from the TU receipts (evidence/match/seg-*.json),
not heuristic inventory spans, so bytes are never double counted:
  * a module whose TU receipt is EXACT/RELOCATED counts its whole extent as matched;
  * otherwise only the sizes of strictly matched functions from its function receipt count.
"""
import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRICT = {'EXACT', 'RELOCATED'}
# module paragraph -> (description, function receipt files)
MODULES = {
    '066A': ('main + shared primitives + 36 Alt images', ['r066a.json']),
    '0B84': ('6 Ctrl images', ['r0b84.json']),
    '0CCD': ('24 fades + dispatcher', ['r0ccd.json']),
    '11C1': ('program logic, options, CRC, loops', ['r11c1.json']),
    '158D': ('text/menu/file UI', ['r158d.json']),
    '17F5': ('logo / DAC helpers', ['r158d-17f5.json']),
    '1899': ('DVDT EGA/VGA backend (TASM)', ['s-asm-1899.json']),
    '19F0': ('DAZPCX PCX save', ['s-asm-19f0.json']),
    '1A72': ('DHUF LZH manual extraction', ['s-asm-1a72.json']),
}


def load(name):
    path = ROOT / 'evidence/match' / name
    return json.loads(path.read_text(encoding='utf-8')) if path.exists() else None


def main():
    rows, tot = [], {'extent': 0, 'matched': 0, 'funcs': 0, 'funcs_ok': 0, 'tu': 0}
    for para, (desc, receipts) in MODULES.items():
        tu = load(f'seg-{para.lower()}.json')
        extent = tu['segment']['original_extent']['length'] if tu else None
        tu_status = tu['status'] if tu else '-'
        results = {}
        for name in receipts:
            data = load(name)
            for r in (data or {}).get('results', []):
                results[r['address'].lower()] = r
        funcs = len(results)
        ok = [r for r in results.values() if r['status'] in STRICT]
        matched = extent if tu_status in STRICT else sum(r['size'] for r in ok)
        rows.append((para, desc, funcs, len(ok), extent, matched, tu_status))
        tot['extent'] += extent or 0
        tot['matched'] += matched or 0
        tot['funcs'] += funcs
        tot['funcs_ok'] += len(ok)
        tot['tu'] += tu_status in STRICT
    out = ['# DAZZLE reconstruction progress',
           '',
           '<!-- Generated by tools/progress.py from evidence/match receipts. Do not edit. -->',
           '',
           'Application code only (the Borland runtime in segment 0 and EMU/MATHL is identified stock',
           'library code and is linked, not reconstructed). Bytes are real module code extents.',
           '',
           '| Module | Contents | Functions strict / receipts | Code extent | Strict bytes | TU level |',
           '|---|---|---:|---:|---:|---|']
    for para, desc, funcs, ok, extent, matched, tu_status in rows:
        out.append(f'| {para} | {desc} | {ok} / {funcs} | {extent or 0:,} | {matched or 0:,} | {tu_status} |')
    out += [f'| **Total** | | **{tot["funcs_ok"]} / {tot["funcs"]}** | **{tot["extent"]:,}** | '
            f'**{tot["matched"]:,}** | **{tot["tu"]} / {len(MODULES)} modules** |', '',
            'Function counts come from the function-level receipts (public functions; module-start static',
            'helpers are proven by the TU receipt). "Strict" = EXACT or RELOCATED under tools/objcmp.py /',
            'segcmp.py / asmcmp.py rules. Link-level and packed-file proofs are tracked in docs/link.md and',
            'docs/packing.md.']
    (ROOT / 'docs/PROGRESS.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('\n'.join(out[7:7 + len(rows) + 3]))


if __name__ == '__main__':
    main()
